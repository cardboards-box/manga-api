namespace MangaBox.Providers.Sources;

public interface ICubariSource : IMangaUrlSource
{
}

internal class CubariSource(
    IApiService _api,
    ILogger<CubariSource> _logger) : BaseMangaSource<CubariSource>, ICubariSource
{
    public override string HomeUrl => "https://cubari.moe";
    public override string Provider => "cubari";
    public override string Name => "Cubari.moe";

    private static bool ValidId(string id) => Regex.IsMatch(id, @"\A[A-Za-z0-9_-]+={0,2}\z");

    public override (bool matches, string? part) MatchesProvider(string url)
    {
        if (!Uri.TryCreate(url, UriKind.Absolute, out var uri) ||
            (uri.Scheme != Uri.UriSchemeHttps && uri.Scheme != Uri.UriSchemeHttp) ||
            !uri.Host.Equals("cubari.moe", StringComparison.OrdinalIgnoreCase) ||
            !uri.IsDefaultPort || !string.IsNullOrEmpty(uri.UserInfo))
            return (false, null);

        var parts = uri.AbsolutePath.Split('/', StringSplitOptions.RemoveEmptyEntries);
        return parts.Length >= 3 && parts[0] == "read" && parts[1] == "gist" && ValidId(parts[2])
            ? (true, parts[2])
            : (false, null);
    }

    private string SeriesUrl(string id) => $"{HomeUrl}/read/gist/{id}/";

    private async Task<Series?> GetSeries(string id, CancellationToken token)
    {
        if (!ValidId(id)) return null;

        try
        {
            // Use the same API as Cubari's reader. It resolves both legacy gist
            // aliases and the base64url GitHub paths generated by facaccimo.
            var series = await _api.Get<Series>(
                $"{HomeUrl}/read/api/gist/series/{id}/", token: token);
            if (series is null || string.IsNullOrWhiteSpace(series.Title) || series.Chapters is null ||
                series.Chapters.Values.Any(chapter => chapter is null))
                throw new JsonException("Cubari returned no title or chapter dictionary.");
            return series;
        }
        catch (Exception ex) when (ex is HttpRequestException or HttpInvalidCodeException or JsonException)
        {
            _logger.LogWarning(ex, "Failed to fetch Cubari series {SeriesId}", id);
            return null;
        }
    }

    // Group IDs in Cubari's API can change between requests. Choose by name so
    // the same translation is used when loading metadata and fetching pages.
    private static KeyValuePair<string, JsonElement>? SelectGroup(Series series, Chapter chapter) =>
        chapter.Groups?.OrderBy(g => GroupName(series, g.Key), StringComparer.Ordinal)
            .ThenBy(g => g.Key, StringComparer.Ordinal)
            .Select(g => (KeyValuePair<string, JsonElement>?)g).FirstOrDefault();

    private static string GroupName(Series series, string id) => series.Groups?.GetValueOrDefault(id) ?? id;

    private static double? Number(string? value) =>
        double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var number) && double.IsFinite(number)
            ? number : null;

    private string AbsoluteUrl(string? value)
    {
        if (string.IsNullOrWhiteSpace(value) || !Uri.TryCreate(new Uri(HomeUrl + "/"), value, out var uri) ||
            (uri.Scheme != Uri.UriSchemeHttps && uri.Scheme != Uri.UriSchemeHttp))
            throw new JsonException("Cubari returned an invalid image or proxy URL.");
        return uri.AbsoluteUri;
    }

    public override async Task<ImportManga?> Manga(string id, CancellationToken token)
    {
        var series = await GetSeries(id, token);
        if (series is null) return null;

        var chapters = new List<ImportChapter>();
        foreach (var (chapterId, chapter) in series.Chapters!)
        {
            var number = Number(chapterId);
            var group = SelectGroup(series, chapter);
            if (number is null || group is null)
            {
                _logger.LogWarning("Skipping Cubari chapter {ChapterId} without a numeric chapter number or group", chapterId);
                continue;
            }

            var attributes = new List<ImportAttribute> { new("Group", GroupName(series, group.Value.Key)) };
            if (chapter.ReleaseDate?.TryGetValue(group.Value.Key, out var date) == true &&
                date.ValueKind is JsonValueKind.String or JsonValueKind.Number)
                attributes.Add(new("Release Date", date.ToString()));

            chapters.Add(new()
            {
                Id = chapterId,
                Number = number.Value,
                Volume = Number(chapter.Volume.ToString()),
                Title = chapter.Title,
                Url = $"{SeriesUrl(id)}{chapterId.Replace('.', '-')}/1/",
                Attributes = attributes
            });
        }

        return new()
        {
            Id = id,
            Provider = Provider,
            HomePage = SeriesUrl(id),
            Title = series.Title,
            Description = series.Description,
            Authors = string.IsNullOrWhiteSpace(series.Author) ? [] : [series.Author],
            Artists = string.IsNullOrWhiteSpace(series.Artist) ? [] : [series.Artist],
            Cover = string.IsNullOrWhiteSpace(series.Cover) ? [] : [AbsoluteUrl(series.Cover)],
            Uploaders = chapters.SelectMany(c => c.Attributes.Where(a => a.Name == "Group").Select(a => a.Value))
                .Distinct(StringComparer.Ordinal).ToArray(),
            Referer = Referer,
            Chapters = chapters.OrderBy(c => c.Number).ToList(),
            OrdinalVolumeReset = false
        };
    }

    public Task<ImportPage[]> ChapterPages(string url, CancellationToken token)
    {
        var (matches, id) = MatchesProvider(url);
        if (!matches || id is null) return Task.FromResult<ImportPage[]>([]);
        var parts = new Uri(url).AbsolutePath.Split('/', StringSplitOptions.RemoveEmptyEntries);
        return parts.Length >= 4
            ? ChapterPages(id, parts[3].Replace('-', '.'), token)
            : Task.FromResult<ImportPage[]>([]);
    }

    public override async Task<ImportPage[]> ChapterPages(string mangaId, string chapterId, CancellationToken token)
    {
        var series = await GetSeries(mangaId, token);
        if (series?.Chapters is null || !series.Chapters.TryGetValue(chapterId, out var chapter) || chapter is null)
            return [];
        var group = SelectGroup(series, chapter);
        if (group is null) return [];

        try
        {
            var pages = group.Value.Value;
            if (pages.ValueKind == JsonValueKind.String)
            {
                var proxyUrl = new Uri(AbsoluteUrl(pages.GetString()));
                // A group string is a Cubari chapter proxy, never an arbitrary
                // JSON endpoint supplied by the gist author.
                if (proxyUrl.Host != "cubari.moe" || proxyUrl.Scheme != Uri.UriSchemeHttps ||
                    !proxyUrl.IsDefaultPort || !string.IsNullOrEmpty(proxyUrl.UserInfo) ||
                    !proxyUrl.AbsolutePath.StartsWith("/proxy/api/", StringComparison.Ordinal))
                    throw new JsonException("Unsupported Cubari chapter proxy URL.");

                pages = await _api.Get<JsonElement>(proxyUrl.AbsoluteUri, token: token);
            }

            if (pages.ValueKind != JsonValueKind.Array)
                throw new JsonException("Cubari chapter pages must be an array.");

            return pages.EnumerateArray().Select(page =>
            {
                // Cubari also permits objects with src and description fields.
                var url = page.ValueKind == JsonValueKind.String ? page.GetString() :
                    page.ValueKind == JsonValueKind.Object && page.TryGetProperty("src", out var src) &&
                    src.ValueKind == JsonValueKind.String ? src.GetString() : null;
                return new ImportPage(AbsoluteUrl(url));
            }).ToArray();
        }
        catch (Exception ex) when (ex is HttpRequestException or HttpInvalidCodeException or JsonException)
        {
            _logger.LogWarning(ex, "Failed to fetch Cubari pages for {SeriesId} chapter {ChapterId}", mangaId, chapterId);
            return [];
        }
    }

    private sealed class Series
    {
        [JsonPropertyName("title")]
        public string Title { get; set; } = string.Empty;
        [JsonPropertyName("description")]
        public string? Description { get; set; }
        [JsonPropertyName("author")]
        public string? Author { get; set; }
        [JsonPropertyName("artist")]
        public string? Artist { get; set; }
        [JsonPropertyName("cover")]
        public string? Cover { get; set; }
        [JsonPropertyName("groups")]
        public Dictionary<string, string>? Groups { get; set; }
        [JsonPropertyName("chapters")]
        public Dictionary<string, Chapter>? Chapters { get; set; }
    }

    private sealed class Chapter
    {
        [JsonPropertyName("title")]
        public string? Title { get; set; }
        [JsonPropertyName("volume")]
        public JsonElement Volume { get; set; }
        [JsonPropertyName("groups")]
        public Dictionary<string, JsonElement>? Groups { get; set; }
        [JsonPropertyName("release_date")]
        public Dictionary<string, JsonElement>? ReleaseDate { get; set; }
    }
}
